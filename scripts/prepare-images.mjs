import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { readFile, readdir, mkdir, writeFile, copyFile, stat } from 'node:fs/promises';
import sharp from 'sharp';

const root = new URL('../', import.meta.url);
const settings = { format: 'webp', quality: 82, effort: 5, maxWidth: 1920, maxHeight: 1080 };
const digest = (data) => createHash('sha256').update(data).digest('hex');
const optimizedPath = (source) => source.replace(/\.png$/i, '.webp');

export async function prepareImages(story) {
  await mkdir(new URL('assets/story/', root), { recursive: true });
  await mkdir(new URL('public/photo/', root), { recursive: true });
  let previous = {};
  try { previous = JSON.parse(await readFile(new URL('assets/image-manifest.json', root), 'utf8')); } catch { /* First build. */ }
  const images = [];
  for (const name of (await readdir(new URL('photo/', root))).filter((name) => /\.png$/i.test(name)).sort()) {
    const source = `photo/${name}`;
    const input = await readFile(new URL(source, root));
    const sourceHash = digest(input);
    const output = `assets/story/${name.replace(/\.png$/i, '.webp')}`;
    const target = new URL(output, root);
    const cached = previous.images?.find((item) => item.source === source && item.sourceHash === sourceHash);
    let exists = false;
    try { exists = (await stat(target)).isFile(); } catch { /* New asset. */ }
    if (!cached || !exists || JSON.stringify(previous.settings) !== JSON.stringify(settings)) {
      await sharp(input).rotate().resize({ width: settings.maxWidth, height: settings.maxHeight, fit: 'inside', withoutEnlargement: true })
        .webp({ quality: settings.quality, effort: settings.effort }).toFile(fileURLToPath(target));
    }
    const data = await readFile(target);
    const metadata = await sharp(data).metadata();
    images.push({ source, sourceHash, output, bytesOriginal: input.length, bytes: data.length, width: metadata.width, height: metadata.height, outputHash: digest(data) });
  }
  const references = [...new Set(story.scenes.map((scene) => scene.image))];
  const entries = [];
  for (const source of references) {
    const item = images.find((entry) => entry.source === source);
    if (!item) throw new Error(`Нет исходного арта: ${source}`);
    const webPath = optimizedPath(source);
    await copyFile(new URL(item.output, root), new URL(`public/${webPath}`, root));
    // Old cached stories still refer to PNG names. Both names resolve to the optimized native asset.
    for (const key of [source, webPath]) entries.push(`  ${JSON.stringify(key)}: require(${JSON.stringify(`../${item.output}`)}),`);
  }
  await writeFile(new URL('src/assets.ts', root), `// Generated by npm run prepare:story. Edit original images in photo/.\nimport type { ImageSourcePropType } from 'react-native';\n\nexport const bundledImages: Record<string, ImageSourcePropType> = {\n${entries.join('\n')}\n};\n`);
  const optimizedStory = { ...story, scenes: story.scenes.map((scene) => ({ ...scene, image: optimizedPath(scene.image) })) };
  await writeFile(new URL('assets/story.json', root), JSON.stringify(optimizedStory, null, 2) + '\n');
  const manifest = { settings, images };
  await writeFile(new URL('assets/image-manifest.json', root), JSON.stringify(manifest, null, 2) + '\n');
  const used = images.filter((item) => references.includes(item.source));
  const original = used.reduce((sum, item) => sum + item.bytesOriginal, 0);
  const bytes = used.reduce((sum, item) => sum + item.bytes, 0);
  console.log(`Арт: ${used.length} изображений, ${(original / 1048576).toFixed(1)} → ${(bytes / 1048576).toFixed(1)} МБ (−${Math.round((1 - bytes / original) * 100)}%). Подготовлено всего: ${images.length}.`);
  return manifest;
}

export async function prepareBranding() {
  const folder = new URL('assets/branding/', root);
  await mkdir(folder, { recursive: true });
  await mkdir(new URL('public/icons/', root), { recursive: true });
  // Crop the existing cover for the launcher icon; never modify the source illustration.
  const portrait = await sharp(await readFile(new URL('photo/scen1.png', root)))
    .flatten({ background: '#15100c' }).extract({ left: 435, top: 35, width: 550, height: 550 }).resize(1024, 1024).png().toBuffer();
  await writeFile(new URL('icon.png', folder), portrait);
  const foreground = await sharp(portrait).resize(640, 640).png().toBuffer();
  await sharp({ create: { width: 1024, height: 1024, channels: 4, background: '#15100c00' } })
    .composite([{ input: foreground, left: 192, top: 192 }]).png().toFile(fileURLToPath(new URL('adaptive-icon.png', folder)));
  const splash = await sharp(portrait).resize(288, 288).png().toBuffer();
  await writeFile(new URL('splash.png', folder), splash);
  for (const size of [192, 512]) await writeFile(new URL(`public/icons/icon-${size}.png`, root), await sharp(portrait).resize(size, size).png().toBuffer());
  await writeFile(new URL('favicon.png', folder), await sharp(portrait).resize(64, 64).png().toBuffer());
  await writeFile(new URL('public/icons/apple-touch-icon.png', root), await sharp(portrait).resize(180, 180).png().toBuffer());
}
